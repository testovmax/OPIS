R.h1('ПРИЛОЖЕНИЕ А. SQL-скрипт создания базы данных', new_page=True)
order = ['uch', 'spec', 'cab', 'diag', 'prep', 'pac', 'vr', 'tal', 'pri', 'rec']
refs = {('pac', 'district_no'): 'District', ('vr', 'specialty_id'): 'Specialty', ('vr', 'room_no'): 'Room',
        ('vr', 'district_no'): 'District', ('tal', 'doctor_id'): 'Doctor', ('tal', 'card_no'): 'Patient',
        ('pri', 'icd_code'): 'Diagnosis', ('rec', 'medicine_id'): 'Medicine'}
sql = []
for k in order:
    name, pn, dep, kk, aa = L.E[k]
    cols = []
    for a in kk + aa:
        nn = '' if 'O' in a[3].split(',') else ' NOT NULL'
        cols.append(f'  {a[1]} {a[2]}{nn}')
    cols.append(f'  CONSTRAINT PK_{pn} PRIMARY KEY ({", ".join(a[1] for a in kk)})')
    for (ek, col), t in refs.items():
        if ek == k:
            cols.append(f'  CONSTRAINT FK_{pn}_{t}_{col} FOREIGN KEY ({col}) REFERENCES {t}')
    if k == 'pri':
        cols.append('  CONSTRAINT FK_Visit_Ticket FOREIGN KEY (doctor_id, visit_date, visit_time) REFERENCES Ticket')
    if k == 'rec':
        cols.append('  CONSTRAINT FK_Prescription_Visit FOREIGN KEY (doctor_id, visit_date, visit_time) REFERENCES Visit')
    if k == 'pac':
        cols.append('  CONSTRAINT AK_Patient_oms UNIQUE (oms_policy)')
    sql.append(f'CREATE TABLE {pn} (\n' + ',\n'.join(cols) + '\n);')
text = '\n\n'.join(sql)
for line in text.split('\n'):
    p = R.p('', indent=False, spacing=1.0, align=0)
    r = p.add_run(line if line else ' ')
    r.font.name = 'Courier New'
    r.font.size = __import__('docx').shared.Pt(9)
open(os.path.join(VIS, 'Поликлиника.sql'), 'w', encoding='utf-8').write(text + '\n')
