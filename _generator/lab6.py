def class_diagram(p):
    B = {}
    for k, (x, y, w, n, at, op, st, ab) in CLASSES.items():
        B[k] = U.uclass(p, x, y, w, n + (' {abstract}' if ab else ''), at, op, stereo=st, abstract=ab, size=6.6)

    def bot(k, x=None):
        X, Y, W, H = B[k]
        return (x if x is not None else X + W / 2, Y + H)

    def top(k, x=None):
        X, Y, W, H = B[k]
        return (x if x is not None else X + W / 2, Y)

    def lft(k, y=None):
        X, Y, W, H = B[k]
        return (X, y if y is not None else Y + H / 2)

    def rgt(k, y=None):
        X, Y, W, H = B[k]
        return (X + W, y if y is not None else Y + H / 2)

    # обобщения
    pt = top('pac', 40)
    U.line(p, [pt, (40, 48), (108, 48), bot('chel', 108)], end='tri')
    U.line(p, [top('sotr', 123), bot('chel', 123)], end='tri')
    U.line(p, [top('reg', 105), bot('sotr', 105)], end='tri')
    U.line(p, [top('vr', 140), bot('sotr', 140)], end='tri')
    # агрегация Участок — Пациент
    U.line(p, [bot('uch', 30), top('pac', 30)], begin='dia')
    U.mult(p, bot('uch', 30), '1', dy=3)
    U.mult(p, top('pac', 30), '0..*', dy=-4.5)
    # Специальность — Врач
    s = bot('spec', 240)
    U.line(p, [s, (240, 46), (172, 46), top('vr', 172)])
    U.mult(p, s, '1', dy=0.5)
    U.mult(p, top('vr', 172), '1..*', dy=-4.5)
    # Врач — Расписание
    y = B['vr'][1] + 14
    U.line(p, [rgt('vr', y), lft('ras', y)])
    U.mult(p, rgt('vr', y), '1', dy=-4.2)
    U.mult(p, lft('ras', y), '0..*', dx=-8, dy=0.3)
    # Расписание ◆— Талон
    U.line(p, [bot('ras', 222), top('tal', 222)], begin='dia_f')
    U.mult(p, bot('ras', 222), '1', dy=7)
    U.mult(p, top('tal', 222), '1..*', dy=-4.5)
    # Регистратор ..> Расписание
    s = bot('reg', 88)
    U.line(p, [s, (88, 140), (204, 140), bot('ras', 204)], dash=True, end='open')
    U.label(p, 150, 136, '«use»', size=7, italic=True)
    # Пациент — Талон
    s = bot('pac', 22)
    U.line(p, [s, (22, 145), (244, 145), top('tal', 244)])
    U.mult(p, s, '0..1', dy=0.5)
    U.mult(p, top('tal', 244), '0..*', dy=-4.5)
    U.label(p, 24, 120, 'записан по', size=6.8, italic=True)
    # Талон — Приём
    y = B['tal'][1] + 10
    U.line(p, [lft('tal', y), rgt('pri', y)])
    U.mult(p, lft('tal', y), '1', dx=-3, dy=-4.2)
    U.mult(p, rgt('pri', y), '0..1', dx=0.5, dy=-4.2)
    # Приём ◆— Рецепт
    y = B['pri'][1] + 10
    U.line(p, [lft('pri', y), rgt('rec', y)], begin='dia_f')
    U.mult(p, rgt('rec', y), '0..*', dx=0.3, dy=0.6)
    U.mult(p, lft('pri', y), '1', dx=-3, dy=0.6)
    # Рецепт — Препарат
    y = B['rec'][1] + 10
    U.line(p, [lft('rec', y), rgt('prep', y)])
    U.mult(p, lft('rec', y), '0..*', dx=-7, dy=-4.2)
    U.mult(p, rgt('prep', y), '1', dx=0.5, dy=-4.2)
    # Приём — Диагноз
    s = bot('diag', 272)
    U.line(p, [s, (272, 136), (178, 136), top('pri', 178)])
    U.mult(p, s, '1', dy=0.5)
    U.mult(p, top('pri', 178), '0..*', dy=-4.5)


def build(d):
    usecase_initial(d.page('Прецеденты (исходная)'))
    usecase_full(d.page('Прецеденты (дополненная)'))
    class_diagram(d.page('Диаграмма классов'))


