def cx(b):
    return b[0] + b[2] / 2


def cy(b):
    return b[1] + b[3] / 2


def R(b):
    return (b[0] + b[2], cy(b))


def L(b):
    return (b[0], cy(b))


def T(b, dx=0):
    return (cx(b) + dx, b[1])


def B(b, dx=0):
    return (cx(b) + dx, b[1] + b[3])


