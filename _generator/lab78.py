def seq(p, title, lls, steps, x0=26, x1=280, y0=16, dy=9.0):
    """lls: [(имя, актёр?)]; steps: ('m', a, b, text) | ('r', a, b, text) | ('s', a, text)
    | ('frag', op, guard, i1, i2) | ('else', guard) | ('end',)"""
    U.title(p, title)
    n = len(lls)
    xs = [x0 + (x1 - x0) * i / (n - 1) for i in range(n)]
    y = y0 + 26
    events = []
    frames = []
    stack = []
    num = 0
    for st in steps:
        k = st[0]
        if k == 'frag':
            stack.append([st[1], st[2], st[3], st[4], y - 3, []])
            y += 7
            continue
        if k == 'else':
            stack[-1][5].append((y - 1.5, st[1]))
            y += 6
            continue
        if k == 'end':
            fr = stack.pop()
            frames.append((fr, y - 2))
            y += 4
            continue
        if k == 'm':
            num += 1
            events.append(('m', st[1], st[2], st[3], y, num))
        elif k == 'r':
            events.append(('r', st[1], st[2], st[3], y, None))
        elif k == 's':
            num += 1
            events.append(('s', st[1], None, st[2], y, num))
            y += 5
        y += dy
    y_end = y + 4
    for i, (nm, is_actor) in enumerate(lls):
        U.lifeline(p, xs[i], y0, nm, y_end, is_actor=is_actor)
    # активации: от первого до последнего события с участием линии
    for i in range(n):
        ys = [e[4] for e in events if e[1] == i or e[2] == i]
        if ys:
            ye = max(ys) + (6 if any(e[0] == 's' and e[1] == i and e[4] == max(ys) for e in events) else 0)
            U.activation(p, xs[i], min(ys) - 1.5, ye + 2)
    for (op, guard, i1, i2, fy, splits), fy2 in frames:
        U.fragment(p, xs[i1] - 14, fy, xs[i2] - xs[i1] + 28, fy2 - fy, op, guard, splits)
    for k, a, b, t, yy, nn in events:
        if k == 's':
            U.self_msg(p, xs[a], yy, t, nn)
        else:
            xa = xs[a] + (1.6 if xs[b] > xs[a] else -1.6)
            xb = xs[b] + (-1.6 if xs[b] > xs[a] else 1.6)
            U.msg(p, xa, xb, yy, t, ret=(k == 'r'), num=nn)


